// Builds src/lib/outils/base-top10.ts from the api graphs Comfy Cloud executed for the
// top-10 measurement runs (scripts/top10/*.api.json, 29.10.2026). Same rules as base.ts:
// preview nodes removed, exactly one save node kept. Templates that save several images
// (the 8 angles) get one Batch Images node feeding a single SaveImage, so one job gives
// every picture from one final node. Run: node scripts/build-top10-bases.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const DIR = new URL("./top10/", import.meta.url);
const OUT = new URL("../src/lib/outils/base-top10.ts", import.meta.url);

/** Final decode node of each angle, in the order the studio names them. */
const ANGLES = ["45_left", "45_right", "90_left", "90_right", "close_up", "wide", "low", "aerial"];
const LOTS = {
  "templates-1_click_multiple_character_angles-v1.0": {
    "45_left": "427:423:420", "45_right": "427:246:243", "90_left": "427:371:368", "90_right": "427:321:318",
    close_up: "427:221:158", wide: "427:296:293", low: "427:346:343", aerial: "427:271:268",
  },
  "templates-1_click_multiple_scene_angles-v1.0": {
    "45_left": "65:46:134", "45_right": "65:37:89", "90_left": "65:40:107", "90_right": "65:39:98",
    close_up: "65:33:19", wide: "65:35:80", low: "65:44:125", aerial: "65:42:116",
  },
};
/** Uploaded sample names are replaced by the template's own input names. */
const SAMPLES = {
  "templates-1_click_multiple_character_angles-v1.0": { "25": { image: "character_input.png" } },
  "templates-1_click_multiple_scene_angles-v1.0": { "25": { image: "comfy_billboard.png" } },
  "template_qwen_multiangle.app": { "1": { image: "cyber_genesis.png" }, "221": { horizontal_angle: 333, vertical_angle: 17, zoom: 5 } },
  audio_melbandroformer_audio_separation: { "1": { audio: "melbandroformer_input.mp3" } },
  api_mirelo_video_to_sfx: { "7": { file: "mage_crash_discovery_video.mp4" } },
  video_minimax_h3_multiframe_reference: { "164": { image: "h3_frame_ref_1.png" }, "167": { image: "h3_frame_ref_4.png" } },
  template_ltx2_3_style_transition: { "137": { image: "ltx23_flf2v_last_frame.png" }, "138": { image: "ltx23_flf2v_first_frame.png" } },
  "templates-portrait_light_migration": { "6": { image: "woman_with_sunbeam.jpg" }, "7": { image: "women_with_blue_orb.jpg" } },
  image_qwen_image_edit_2509_relight: { "11": { image: "warm_living_room.png" }, "15": { value: " relight the image using twilight light (with a warm color temperature, soft light, and blurred shadows)" } },
};
/** Extra outputs the studio does not read: the second stem, the speech track, the re-muxed video. */
const DROP = {
  audio_melbandroformer_audio_separation: [/^5$/],
  api_mirelo_video_to_sfx: [/^5$/, /^730$/, /^729:/],
  // Two pictures in the studio: the middle guides (1.5 s and 3 s) go, the 5 s guide stays.
  video_minimax_h3_multiframe_reference: [/^(147|153|154|157|159|160|161|162)$/],
};
/** Links rewired after DROP so the graph stays whole. */
const REWIRE = {
  video_minimax_h3_multiframe_reference: { "169": { positive: ["136", 0] } },
};
const SAVE = /^(Save|VHS_VideoCombine$)/;

const bases = {};
for (const file of readdirSync(DIR).filter(name => name.endsWith(".api.json")).sort()) {
  const template = file.replace(/\.api\.json$/, "");
  const graph = JSON.parse(readFileSync(new URL(file, DIR), "utf8"));
  for (const [id, node] of Object.entries(graph)) if (/^Preview/.test(node.class_type)) delete graph[id];
  for (const [id, values] of Object.entries(SAMPLES[template] ?? {})) Object.assign(graph[id].inputs, values);
  for (const pattern of DROP[template] ?? []) for (const id of Object.keys(graph)) if (pattern.test(id)) delete graph[id];
  for (const [id, values] of Object.entries(REWIRE[template] ?? {})) Object.assign(graph[id].inputs, values);
  const lot = LOTS[template];
  if (lot) {
    for (const [id, node] of Object.entries(graph)) if (SAVE.test(node.class_type)) delete graph[id];
    graph["990"] = { inputs: Object.fromEntries(ANGLES.map((angle, index) => [`images.image${index}`, [lot[angle], 0]])), class_type: "BatchImagesNode", _meta: { title: "Batch Images" } };
    graph["991"] = { inputs: { filename_prefix: "Angles", images: ["990", 0] }, class_type: "SaveImage", _meta: { title: "Save Image" } };
  }
  const saves = Object.entries(graph).filter(([, node]) => SAVE.test(node.class_type));
  if (saves.length !== 1) throw new Error(`${template}: ${saves.length} save nodes`);
  bases[template] = graph;
}

const body = JSON.stringify(bases, null, 1);
writeFileSync(OUT, `// Generated by scripts/build-top10-bases.mjs from the api graphs Comfy Cloud ran on 29.10.2026.
// Preview nodes removed; one save node kept. Do not edit by hand.

import type { ApiGraph } from "../render/take-graph.ts";

/** Angle order of the 8-image lots (Batch Images node 990, save 991). */
export const ANGLES_LOT = ${JSON.stringify(ANGLES)} as const;

export const TOP10_BASES: Record<string, ApiGraph> = ${body};
`);
console.log(Object.keys(bases).join("\n"));
